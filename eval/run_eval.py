"""Evaluate medsafe against hand-labeled synthetic cases.

Two evaluations:

1. Checks: 32 patient cases in eval/cases.json, each with the findings a
   reviewer would expect, keyed by (category, drugs). Severity is not scored.
2. Extraction: 10 free-text notes in eval/notes/ with gold medication lists.
   Compares the regex baseline with the LLM extractor (when --llm is given).

Usage:
  python eval/run_eval.py                 # checks + rules extraction, writes eval/RESULTS.md
  python eval/run_eval.py --llm           # also runs LLM extraction (needs credentials)
  python eval/run_eval.py --check         # exit 1 if metrics fall below eval/baseline.json
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "src"))

from medsafe.extract import extract_llm, extract_rules  # noqa: E402
from medsafe.pipeline import patient_from_dict, run  # noqa: E402


def prf(tp: int, fp: int, fn: int):
    p = tp / (tp + fp) if tp + fp else 1.0
    r = tp / (tp + fn) if tp + fn else 1.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return p, r, f


def eval_checks():
    cases = json.loads((ROOT / "cases.json").read_text())
    per_cat = defaultdict(lambda: [0, 0, 0])
    misses, extras = [], []
    for case in cases:
        patient = patient_from_dict({"id": case["id"], **case["patient"]})
        got = {(f.category, tuple(sorted(f.drugs))) for f in run(patient).findings}
        exp = {(e["category"], tuple(sorted(e["drugs"]))) for e in case["expected"]}
        for k in got & exp:
            per_cat[k[0]][0] += 1
        for k in got - exp:
            per_cat[k[0]][1] += 1
            extras.append((case["id"], k))
        for k in exp - got:
            per_cat[k[0]][2] += 1
            misses.append((case["id"], k, case.get("notes", "")))
    tot = [sum(v[i] for v in per_cat.values()) for i in range(3)]
    return len(cases), per_cat, tot, misses, extras


def _match_meds(pred, gold):
    gold_by_name = {g["name"]: g for g in gold}
    pred_names = {m.name for m in pred}
    tp = len(pred_names & set(gold_by_name))
    exact = 0
    for m in pred:
        g = gold_by_name.get(m.name)
        if g and m.dose == g["dose"] and (m.unit or None) == g["unit"] and m.doses_per_day == g["doses_per_day"]:
            exact += 1
    return tp, len(pred_names) - tp, len(gold_by_name) - tp, exact


def eval_extraction(method: str, client=None):
    gold = json.loads((ROOT / "notes_gold.json").read_text())
    TP = FP = FN = EX = 0
    for note_id, meds in sorted(gold.items()):
        text = (ROOT / "notes" / f"{note_id}.txt").read_text()
        pred = extract_rules(text) if method == "rules" else extract_llm(text, client)
        tp, fp, fn, ex = _match_meds(pred, meds)
        TP, FP, FN, EX = TP + tp, FP + fp, FN + fn, EX + ex
    p, r, f = prf(TP, FP, FN)
    return {"precision": p, "recall": r, "f1": f,
            "exact_dose_freq": EX / (TP + FN) if TP + FN else 0.0, "tp": TP, "fp": FP, "fn": FN}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--llm", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    n, per_cat, tot, misses, extras = eval_checks()
    p, r, f = prf(*tot)
    ext = {"rules": eval_extraction("rules")}
    if args.llm:
        from medsafe.llm import client_from_env
        ext["llm"] = eval_extraction("llm", client_from_env())

    out = ["# Evaluation results", "",
           "Generated by `python eval/run_eval.py`. All data is synthetic and hand-labeled.", "",
           f"## Safety checks ({n} cases)", "",
           "| Category | TP | FP | FN | Precision | Recall |", "|---|---|---|---|---|---|"]
    for cat in sorted(per_cat):
        tp, fp, fn = per_cat[cat]
        cp, cr, _ = prf(tp, fp, fn)
        out.append(f"| {cat} | {tp} | {fp} | {fn} | {cp:.2f} | {cr:.2f} |")
    out.append(f"| **all** | {tot[0]} | {tot[1]} | {tot[2]} | **{p:.2f}** | **{r:.2f}** |")
    out += ["", "### Missed (false negatives)", ""]
    out += [f"- {cid}: {k[0]} {list(k[1])}. {note}" for cid, k, note in misses] or ["- none"]
    out += ["", "### Unexpected (false positives)", ""]
    out += [f"- {cid}: {k[0]} {list(k[1])}" for cid, k in extras] or ["- none"]
    out += ["", "## Medication extraction (10 notes)", "",
            "| Method | Precision | Recall | F1 | Exact dose+unit+frequency |", "|---|---|---|---|---|"]
    for method, m in ext.items():
        out.append(f"| {method} | {m['precision']:.2f} | {m['recall']:.2f} | {m['f1']:.2f} "
                   f"| {m['exact_dose_freq']:.2f} |")
    if "llm" not in ext:
        out.append("| llm | not run here: requires credentials. Run `python eval/run_eval.py --llm` | | | |")
    (ROOT / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))

    if args.check:
        base = json.loads((ROOT / "baseline.json").read_text())
        ok = p >= base["checks_precision"] and r >= base["checks_recall"] \
            and ext["rules"]["f1"] >= base["rules_extraction_f1"]
        if not ok:
            print("\nREGRESSION: metrics fell below eval/baseline.json", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
