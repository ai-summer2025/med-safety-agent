"""
Report generation and formatting for the Drug Safety Agent.
"""
from typing import Optional
from models import PatientSafetyReport, RiskLevel


RISK_COLORS = {
    RiskLevel.LOW: "🟢",
    RiskLevel.MEDIUM: "🟡",
    RiskLevel.HIGH: "🟠",
    RiskLevel.CRITICAL: "🔴",
}


def format_report(report: PatientSafetyReport) -> str:
    """Format a PatientSafetyReport as a human-readable string."""
    lines = []

    lines.append("=" * 72)
    lines.append("  DRUG SAFETY AGENT — PATIENT MEDICATION SAFETY REPORT")
    lines.append("=" * 72)
    lines.append(f"  Patient ID  : {report.patient_id}")
    lines.append(f"  Medications : {len(report.medications)}")
    lines.append(f"  Agent Runs  : {report.agent_iterations}")
    lines.append(f"  API Calls   : {report.total_api_calls}")
    lines.append(
        f"  OVERALL RISK: {RISK_COLORS[report.overall_risk]} {report.overall_risk.value}"
    )
    lines.append("=" * 72)

    # Per-medication risk table
    lines.append("\n📊 INDIVIDUAL MEDICATION RISK PROFILES")
    lines.append("-" * 72)
    header = f"{'Medication':<22} {'Risk':<10} {'Total Reports':>15} {'Serious':>10}"
    lines.append(header)
    lines.append("-" * 72)

    for profile in report.medication_profiles:
        icon = RISK_COLORS.get(profile.risk_level, "")
        lines.append(
            f"{profile.medication.name:<22} "
            f"{icon} {profile.risk_level.value:<7} "
            f"{profile.total_event_count:>15,} "
            f"{profile.serious_event_count:>10,}"
        )
        if profile.top_reactions:
            top3 = ", ".join(profile.top_reactions[:3])
            lines.append(f"  Top reactions: {top3}")

    # Drug interactions
    lines.append("\n🔗 DRUG-DRUG INTERACTIONS")
    lines.append("-" * 72)
    if report.interactions:
        for ix in report.interactions:
            icon = "🚨" if ix.is_serious else "⚠️ "
            lines.append(f"{icon} {ix.drug_a} ↔ {ix.drug_b}")
            lines.append(f"   Severity: {ix.severity.upper()}")
            desc = ix.description
            if len(desc) > 100:
                desc = desc[:97] + "..."
            lines.append(f"   Detail: {desc}")
    else:
        lines.append("  ✅ No significant drug interactions detected.")

    # Critical alerts
    lines.append("\n🚨 CRITICAL ALERTS")
    lines.append("-" * 72)
    if report.critical_alerts:
        for alert in report.critical_alerts:
            lines.append(f"  {alert}")
    else:
        lines.append("  ✅ No critical alerts.")

    # Recommendations
    lines.append("\n💊 RECOMMENDATIONS")
    lines.append("-" * 72)
    for i, rec in enumerate(report.recommendations, 1):
        lines.append(f"  {i}. {rec}")

    lines.append("\n" + "=" * 72)
    lines.append("  Report generated by Drug Safety Agent (openFDA + RxNav APIs)")
    lines.append("  ⚠️  For clinical use by licensed healthcare professionals only.")
    lines.append("=" * 72)

    return "\n".join(lines)


def report_to_dict(report: PatientSafetyReport) -> dict:
    """Convert report to a serializable dictionary."""
    return {
        "patient_id": report.patient_id,
        "overall_risk": report.overall_risk.value,
        "medications": [
            {
                "name": m.name,
                "dose": m.dose,
                "rxcui": m.rxcui,
            }
            for m in report.medications
        ],
        "medication_profiles": [
            {
                "medication": p.medication.name,
                "risk_level": p.risk_level.value,
                "total_event_count": p.total_event_count,
                "serious_event_count": p.serious_event_count,
                "top_reactions": p.top_reactions[:5],
            }
            for p in report.medication_profiles
        ],
        "interactions": [
            {
                "drug_a": ix.drug_a,
                "drug_b": ix.drug_b,
                "severity": ix.severity,
                "description": ix.description,
            }
            for ix in report.interactions
        ],
        "critical_alerts": report.critical_alerts,
        "recommendations": report.recommendations,
        "agent_iterations": report.agent_iterations,
        "total_api_calls": report.total_api_calls,
    }
